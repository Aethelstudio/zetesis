CREATE TABLE users(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT UNIQUE NOT NULL,salt TEXT NOT NULL,pw TEXT NOT NULL);
CREATE TABLE sessions(token TEXT PRIMARY KEY,user_id INTEGER NOT NULL,exp INTEGER NOT NULL);
CREATE TABLE data(user_id INTEGER PRIMARY KEY,json TEXT NOT NULL,upd INTEGER NOT NULL);
CREATE TABLE usage(user_id INTEGER,day TEXT,n INTEGER,PRIMARY KEY(user_id,day));
